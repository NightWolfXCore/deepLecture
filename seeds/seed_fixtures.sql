       MIN(s.start_ms), MAX(s.end_ms),
       GROUP_CONCAT(s.text ORDER BY s.position SEPARATOR ' '),
       (SELECT x.id FROM transcript_segments x
         WHERE x.lecture_id = 'a0000000-0000-4000-8000-000000000002' AND x.position = d.from_pos),
       (SELECT x.id FROM transcript_segments x
         WHERE x.lecture_id = 'a0000000-0000-4000-8000-000000000002' AND x.position = d.to_pos)
FROM (
    SELECT 'd1000000-0000-4000-8000-000000000000' AS id, 0 AS position, 0 AS from_pos, 2 AS to_pos
    UNION ALL SELECT 'd1000000-0000-4000-8000-000000000001', 1, 2, 4
    UNION ALL SELECT 'd1000000-0000-4000-8000-000000000002', 2, 4, 6
    UNION ALL SELECT 'd1000000-0000-4000-8000-000000000003', 3, 6, 8
    UNION ALL SELECT 'd1000000-0000-4000-8000-000000000004', 4, 8, 9
) d
JOIN transcript_segments s
  ON s.lecture_id = 'a0000000-0000-4000-8000-000000000002'
